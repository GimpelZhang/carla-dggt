    def test_generate_comparison_report(self, nurec_reference_data, tmp_path):
        """Generate detailed comparison report"""
        if nurec_reference_data is None:
            pytest.skip("No NuRec reference data available")

        report_lines = ["# Coordinate Transform Comparison Report\n\n"]
        report_lines.append("Generated by test_nurec_comparison.py\n\n")

        # Camera poses section
        report_lines.append("## Camera Poses\n\n")
        camera_errors = []
        for sample in nurec_reference_data.get('camera_poses', []):
            carla_pose = np.array(sample['carla_pose'])
            nurec_result = np.array(sample['nurec_pose'])
            our_result = CoordinateTransform.transform_pose_carla_to_dggt(carla_pose)

            pos_error = np.max(np.abs(our_result[:3, 3] - nurec_result[:3, 3]))
            rot_error = np.max(np.abs(our_result[:3, :3] - nurec_result[:3, :3]))
            camera_errors.append((pos_error, rot_error))

            report_lines.append(f"- Sample {sample.get('id', 'unknown')}:\n")
            report_lines.append(f"  - Position error: {pos_error:.6e}\n")
            report_lines.append(f"  - Rotation error: {rot_error:.6e}\n")

        # Dynamic objects section
        report_lines.append("\n## Dynamic Objects\n\n")
        object_errors = []
        for sample in nurec_reference_data.get('dynamic_objects', []):
            carla_pose = np.array(sample['carla_pose'])
            nurec_result = np.array(sample['nurec_pose'])
            our_result = CoordinateTransform.transform_pose_carla_to_dggt(carla_pose)

            pos_error = np.max(np.abs(our_result[:3, 3] - nurec_result[:3, 3]))
            rot_error = np.max(np.abs(our_result[:3, :3] - nurec_result[:3, :3]))
            object_errors.append((pos_error, rot_error))

            report_lines.append(f"- Object {sample.get('track_id', 'unknown')}:\n")
            report_lines.append(f"  - Position error: {pos_error:.6e}\n")
            report_lines.append(f"  - Rotation error: {rot_error:.6e}\n")

        # Summary section
        report_lines.append("\n## Summary\n\n")
        all_errors = camera_errors + object_errors
        if all_errors:
            max_pos_err = max(e[0] for e in all_errors)
            max_rot_err = max(e[1] for e in all_errors)
            mean_pos_err = np.mean([e[0] for e in all_errors])
            mean_rot_err = np.mean([e[1] for e in all_errors])

            report_lines.append(f"- **Max position error**: {max_pos_err:.6e}\n")
            report_lines.append(f"- **Max rotation error**: {max_rot_err:.6e}\n")
            report_lines.append(f"- **Mean position error**: {mean_pos_err:.6e}\n")
            report_lines.append(f"- **Mean rotation error**: {mean_rot_err:.6e}\n")
            report_lines.append(f"- **All within tolerance (1e-5)**: {all(e[0] < 1e-5 and e[1] < 1e-5 for e in all_errors)}\n")

        # Write report
        report_path = tmp_path / "comparison_report.md"
        report_path.write_text("".join(report_lines))
        print(f"\nComparison report written to: {report_path}")

        # Final assertion
        assert all(e[0] < 1e-5 and e[1] < 1e-5 for e in all_errors), "Some transforms exceed tolerance"

    def test_basic_carla_to_dggt_roundtrip(self, sample_carla_pose):
        """Test roundtrip CARLA -> DGGT -> CARLA transformation"""
        # Transform to DGGT
        dggt_pose = CoordinateTransform.transform_pose_carla_to_dggt(sample_carla_pose)

        # Transform back to CARLA
        carla_back = CoordinateTransform.transform_pose_dggt_to_carla(dggt_pose)

        # Should match original (within numerical precision - 1e-6 for float64 operations)
        assert np.allclose(sample_carla_pose, carla_back, atol=1e-6), \
            f"Roundtrip failed: original vs recovered mismatch"

    def test_transform_identity_pose(self):
        """Test transformation of identity pose matrix"""
        identity_pose = np.eye(4, dtype=np.float64)

        # Transform to DGGT
        dggt_pose = CoordinateTransform.transform_pose_carla_to_dggt(identity_pose)

        # Check rotation part matches expected CARLA_TO_DGGT rotation
        expected_rot = CoordinateTransform.CARLA_TO_DGGT_ROTATION
        assert np.allclose(dggt_pose[:3, :3], expected_rot, atol=1e-10), \
            "Identity pose rotation should match CARLA_TO_DGGT_ROTATION"

    def test_transform_point_forward(self):
        """Test that CARLA forward vector transforms to DGGT forward (Z-axis)"""
        # CARLA forward = [1, 0, 0]
        carla_forward = np.array([1.0, 0.0, 0.0])

        dggt_point = CoordinateTransform.transform_point_carla_to_dggt(carla_forward)

        # DGGT forward is Z-axis: [0, 0, 1]
        expected_dggt_forward = np.array([0.0, 0.0, 1.0])
        assert np.allclose(dggt_point, expected_dggt_forward, atol=1e-10), \
            f"CARLA forward should map to DGGT Z-forward: got {dggt_point}"

    def test_transform_point_right(self):
        """Test that CARLA right vector transforms to DGGT right (X-axis)"""
        # CARLA right = [0, 1, 0]
        carla_right = np.array([0.0, 1.0, 0.0])

        dggt_point = CoordinateTransform.transform_point_carla_to_dggt(carla_right)

        # DGGT right is X-axis: [1, 0, 0]
        expected_dggt_right = np.array([1.0, 0.0, 0.0])
        assert np.allclose(dggt_point, expected_dggt_right, atol=1e-10), \
            f"CARLA right should map to DGGT X-right: got {dggt_point}"

    def test_transform_point_up(self):
        """Test that CARLA up vector transforms to DGGT down (negative Y-axis)"""
        # CARLA up = [0, 0, 1]
        carla_up = np.array([0.0, 0.0, 1.0])

        dggt_point = CoordinateTransform.transform_point_carla_to_dggt(carla_up)

        # DGGT Y is Down, so CARLA Up maps to negative Y: [0, -1, 0]
        expected_dggt_down = np.array([0.0, -1.0, 0.0])
        assert np.allclose(dggt_point, expected_dggt_down, atol=1e-10), \
            f"CARLA up should map to DGGT -Y (down): got {dggt_point}"


