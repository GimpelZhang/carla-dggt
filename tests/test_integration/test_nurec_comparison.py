class TestNuRecCoordinateComparison:
    """Compare coordinate transforms with NuRec reference data"""

    @pytest.fixture
    def nurec_reference_data(self):
        """Load NuRec reference data from test fixtures"""
        ref_path = Path(__file__).parent.parent / "test_data" / "nurec_reference" / "coordinate_transforms.json"
        if ref_path.exists():
            with open(ref_path) as f:
                return json.load(f)
        return None

    @pytest.fixture
    def sample_carla_pose(self):
        """Sample CARLA camera pose matrix for basic tests"""
        # 4x4 pose matrix: rotation + translation
        # CARLA coordinate: X=Forward, Y=Right, Z=Up
        # Use simple rotation (no pitch) for roundtrip test stability
        pose = np.array([
            [ 1.0,  0.0,  0.0,  10.0],  # Forward 10m
            [ 0.0,  1.0,  0.0,   5.0],  # Right 5m
            [ 0.0,  0.0,  1.0,   2.0],  # Up 2m
            [ 0.0,  0.0,  0.0,   1.0]
        ], dtype=np.float64)
        return pose

    def test_compare_camera_pose_transform(self, nurec_reference_data):
        """Compare camera pose transforms with NuRec reference"""
        if nurec_reference_data is None:
            pytest.skip("No NuRec reference data available")

        errors = []
        for sample in nurec_reference_data.get('camera_poses', []):
            carla_pose = np.array(sample['carla_pose'])
            nurec_result = np.array(sample['nurec_pose'])

            # Use our transform
            our_result = CoordinateTransform.transform_pose_carla_to_dggt(carla_pose)

            # Compare position component
            pos_error = np.max(np.abs(our_result[:3, 3] - nurec_result[:3, 3]))
            # Compare rotation component (normalized)
            rot_error = np.max(np.abs(our_result[:3, :3] - nurec_result[:3, :3]))

            errors.append((pos_error, rot_error))

            assert np.allclose(our_result, nurec_result, atol=1e-6), \
                f"Mismatch in camera pose transform for sample {sample.get('id', 'unknown')}: pos_err={pos_error:.6e}, rot_err={rot_error:.6e}"

        # Report summary
        if errors:
            max_pos_err = max(e[0] for e in errors)
            max_rot_err = max(e[1] for e in errors)
            print(f"\nCamera pose transform comparison: max_pos_err={max_pos_err:.6e}, max_rot_err={max_rot_err:.6e}")

