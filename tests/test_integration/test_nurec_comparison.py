class TestGenerateComparisonReport:
    """Report generation tests"""

    def test_report_structure(self, tmp_path):
        """Test that report has correct structure"""
        # Create minimal reference data
        ref_data = {
            'camera_poses': [
                {
                    'id': 'test_001',
                    'carla_pose': [[1,0,0,10],[0,1,0,0],[0,0,1,2],[0,0,0,1]],
                    'nurec_pose': [[0,1,0,0],[0,0,-1,-2],[1,0,0,10],[0,0,0,1]]
                }
            ],
            'dynamic_objects': []
        }

        # Save temporary reference
        ref_dir = tmp_path / "nurec_reference"
        ref_dir.mkdir()
        ref_file = ref_dir / "coordinate_transforms.json"
        with open(ref_file, 'w') as f:
            json.dump(ref_data, f)

        # Generate report
        report_lines = ["# Coordinate Transform Comparison Report\n\n"]
        for sample in ref_data['camera_poses']:
            carla_pose = np.array(sample['carla_pose'])
            nurec_result = np.array(sample['nurec_pose'])
            our_result = CoordinateTransform.transform_pose_carla_to_dggt(carla_pose)

            error = np.max(np.abs(our_result - nurec_result))
            report_lines.append(f"- Sample {sample['id']}: error = {error:.6e}\n")

        report_path = tmp_path / "test_report.md"
        report_path.write_text("".join(report_lines))

        # Verify report exists and has content
        assert report_path.exists()
        content = report_path.read_text()
        assert "Coordinate Transform Comparison Report" in content
        assert "test_001" in content